#!/usr/bin/env python3
"""Safely characterize STM32F411 HSI trim using ST-Link + COM7 on Windows.

The AUTOTUNE firmware uses a nominal 80 MHz PLL (not production 100 MHz),
keeps motors OFF, and reports its trim / RCC clock fault on EVERY CLK frame.
This script never changes HSITRIM live, and it always attempts to reflash the
standard default environment after measurements or exceptions.

Requirements: python -m platformio, pyserial; matplotlib is optional.
Quick start:
    python tools/hsi_autotune.py --self-test
    python tools/hsi_autotune.py --port COM7 --start 20 --end 26 --seconds 60
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import math
import pathlib
import statistics
import subprocess
import sys
import time

from clock_serial_test import (FIELDS, analyze, format_summary, parse_clk, plots)

ROOT = pathlib.Path(__file__).resolve().parents[1]
PIO_CONF = ROOT / ".pio" / "hsi_autotune_project.ini"
SAFE_ENV = "genericSTM32F411CE"
AUTO_ENV = "hsi_autotune"
AUTO_NOMINAL_HZ = 80_000_000
LOWER_TRIM, UPPER_TRIM = 16, 26
ABSOLUTE_STOP_MHZ = 90.0  # extra guard, far below F411 100 MHz limit
MIN_RECORDS = 38
MAX_P95_MS = 30.0


class TuningError(RuntimeError):
    pass


def parse_kv(line: str) -> dict[str, str]:
    fields = {}
    for component in line.split(",")[1:]:
        key, equal, val = component.partition("=")
        if equal:
            fields[key.strip()] = val.strip()
    return fields


def validate_motor_off_firmware():
    """Fail closed if the repository is no longer the isolated IMU harness."""
    main = (ROOT / "src" / "main.c").read_text(encoding="utf-8")
    board = (ROOT / "src" / "board.c").read_text(encoding="utf-8")
    required = (
        "/* Old motor + encoder diagnostic harness is intentionally disabled. */\n#if 0",
        "[BOOT] Isolated MPU6050/I2C test (motors disabled)",
        "CLK,seq=%lu,us=%lu,ticks=%lu,tx_drop=%lu,trim=%lu,fault=%lu,sysclk_nominal=%lu",
    )
    for fragment in required:
        if fragment not in main:
            raise TuningError("Cannot verify safe motor-OFF firmware / CLK telemetry. Stop.")
    if "BOARD_PLLN 160UL" not in board or "BOARD_PLLN 200UL" not in board:
        raise TuningError("Cannot verify the safe 80 MHz autotune PLL profile. Stop.")


def temporary_config(trim: int) -> pathlib.Path:
    """Generate an ignored PlatformIO project-conf (no tracked files edited)."""
    original = (ROOT / "platformio.ini").read_text(encoding="utf-8")
    if f"[env:{AUTO_ENV}]" in original:
        raise TuningError("Auto environment name already exists in platformio.ini.")
    extension = (
        "\n; Generated by tools/hsi_autotune.py; never edit tracked config.\n"
        f"[env:{AUTO_ENV}]\n"
        f"extends = env:{SAFE_ENV}\n"
        f"build_flags = -DCLOCK_AUTOTUNE=1 -DCLOCK_HSI_TRIM={trim}\n"
    )
    PIO_CONF.parent.mkdir(parents=True, exist_ok=True)
    PIO_CONF.write_text(original + extension, encoding="utf-8")
    return PIO_CONF


def platformio_command(environment: str, *, project_conf: pathlib.Path | None = None,
                       clean: bool = False) -> list[str]:
    cmd = [sys.executable, "-m", "platformio", "run",
           "--project-dir", str(ROOT)]
    if project_conf is not None:
        cmd += ["--project-conf", str(project_conf)]
    cmd += ["--environment", environment]
    cmd += ["--target", "clean" if clean else "upload"]
    return cmd


def run_command(cmd: list[str]):
    print("\n$ " + subprocess.list2cmdline(cmd), flush=True)
    # A failure must never be interpreted as successful flashing.
    ret = subprocess.run(cmd, cwd=ROOT, check=False)
    if ret.returncode:
        raise TuningError(f"PlatformIO failed (exit={ret.returncode}).")


def save_csv(folder: pathlib.Path, rows: list[dict]):
    with (folder / "clock_samples.csv").open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def capture(port: str, baud: int, seconds: float, trim: int, folder: pathlib.Path,
            *, verbose: bool = True) -> tuple[dict, dict]:
    try:
        import serial
    except ImportError as exc:
        raise TuningError("pyserial missing: python -m pip install pyserial") from exc

    folder.mkdir(parents=True, exist_ok=True)
    rows = []
    telemetry_count = 0
    last_report = -1
    bad_frame = None
    early_abort = None
    start_ns = time.perf_counter_ns()
    raw_file = folder / "raw_serial.log"
    try:
        with serial.Serial(port, baud, timeout=0.25) as ser:
            ser.reset_input_buffer()
            start_ns = time.perf_counter_ns()
            with raw_file.open("w", encoding="utf-8") as raw:
                while (time.perf_counter_ns() - start_ns) * 1e-9 < seconds:
                    packet = ser.readline()
                    current_ns = time.perf_counter_ns()
                    if not packet:
                        continue
                    host_s = (current_ns - start_ns) * 1e-9
                    line = packet.decode("utf-8", errors="replace").strip()
                    raw.write(f"{host_s:.9f}\t{line}\n")
                    value = parse_clk(line)
                    if value is None:
                        continue
                    fields = parse_kv(line)
                    try:
                        active = int(fields["trim"])
                        fault = int(fields["fault"])
                        nominal = int(fields["sysclk_nominal"])
                    except (KeyError, ValueError):
                        bad_frame = "CLK does not expose trim/fault/sysclk_nominal"
                        break
                    if active != trim or fault != 0 or nominal != AUTO_NOMINAL_HZ:
                        bad_frame = (f"CLK firmware mismatch: trim={active} expected={trim}, "
                                     f"fault={fault}, nominal={nominal}")
                        break
                    telemetry_count += 1
                    rows.append({
                        "host_iso": dt.datetime.now(dt.timezone.utc).isoformat(),
                        "host_perf_s": host_s,
                        "session": 0,
                        "seq": value["seq"],
                        "mcu_us": value["us"],
                        "ticks": value["ticks"],
                        "tx_drop": value["tx_drop"],
                    })
                    if verbose and telemetry_count // 10 != last_report:
                        last_report = telemetry_count // 10
                        if telemetry_count >= 10:
                            print(f"  trim {trim:2d}: {telemetry_count:3d} CLK records, "
                                  f"{host_s:5.1f} host seconds", flush=True)

                    # Emergency early slope check, only within a contiguous sequence.
                    if len(rows) >= 12:
                        tail = rows[-12:]
                        first, last = tail[0], tail[-1]
                        ds = (last["mcu_us"] - first["mcu_us"]) / 1e6
                        hs = last["host_perf_s"] - first["host_perf_s"]
                        if ds > 8 and hs > 8 and last["seq"] - first["seq"] == 11:
                            early_mhz = AUTO_NOMINAL_HZ * ds / hs / 1e6
                            if early_mhz >= ABSOLUTE_STOP_MHZ:
                                early_abort = (f"Early slope indicates SYSCLK ~{early_mhz:.3f} "
                                               f"MHz >= {ABSOLUTE_STOP_MHZ:g} MHz guard")
                                break
    except Exception as exc:
        if isinstance(exc, (KeyboardInterrupt, SystemExit)):
            raise
        raise TuningError(f"Serial capture failed on {port}: {exc}") from exc
    finally:
        # raw_serial.log is written even when the session is invalid.
        save_csv(folder, rows)

    if bad_frame or early_abort:
        raise TuningError(bad_frame or early_abort)
    if len(rows) < MIN_RECORDS:
        raise TuningError(f"Only {len(rows)} CLK frames; need >= {MIN_RECORDS}.")
    try:
        report, used, device_s, host_s, predicted = analyze(rows)
    except (ValueError, ZeroDivisionError) as exc:
        raise TuningError(f"Cannot analyze CLK data: {exc}") from exc

    (folder / "clock_summary.txt").write_text(format_summary(report), encoding="utf-8")
    plots(folder, used, device_s, host_s, predicted)
    metrics = validate_measurement(report, seconds=seconds)
    (folder / "autotune_metrics.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    return report, metrics


def validate_measurement(report: dict, *, seconds: float) -> dict:
    hz = report["effective_tim5_hz"]
    measured_mhz = AUTO_NOMINAL_HZ / 1e6 * hz / 1e6
    ratio = report["pc_seconds_per_mcu_second"]
    robust30 = report.get("robust_30s_pc_per_mcu")
    if report["fit_records"] < MIN_RECORDS or report["seq_missing_count"]:
        raise TuningError("Not enough consecutive clock records; stop autotune.")
    if report["tx_drop_delta"] != 0:
        raise TuningError(
            f"Firmware UART TX queue dropped {int(report['tx_drop_delta'])} messages; "
            f"CLK sequence missing={int(report['seq_missing_count'])}. "
            "Autotune refuses to continue until TX congestion is resolved.")
    if not math.isfinite(hz) or not math.isfinite(ratio) or hz <= 0:
        raise TuningError("Invalid frequency estimate; stop autotune.")
    if robust30 is None or abs(robust30 - ratio) > 0.003:
        raise TuningError("Clock estimate fails 30-second stability cross-check.")
    if report["fit_residual_p95_ms"] > MAX_P95_MS:
        raise TuningError("Host USB/serial jitter too high; stop autotune.")
    if measured_mhz >= ABSOLUTE_STOP_MHZ:
        raise TuningError("Autotune measured SYSCLK over 90 MHz guard; stop.")
    return {
        "nominal_profile_mhz": 80,
        "measured_sysclk_mhz": round(measured_mhz, 6),
        "effective_tim5_hz": round(hz, 3),
        "effective_tim11_hz": round(report["effective_tim11_hz"], 3),
        "clock_error_pct": round(report["mcu_clock_rate_error_pct"], 6),
        "fit_records": int(report["fit_records"]),
        "seq_missing_count": int(report["seq_missing_count"]),
        "tx_drop_delta": int(report["tx_drop_delta"]),
        "host_span_s": round(report["host_span_s"], 3),
        "pc_seconds_per_mcu_second": round(ratio, 8),
        "source": "Windows perf_counter + USB/UART; approximate, not a reference oscillator",
    }


def autotune(args):
    validate_motor_off_firmware()
    if not (LOWER_TRIM <= args.start <= args.end <= UPPER_TRIM):
        raise TuningError(f"Bounded auto-scan supports {LOWER_TRIM}..{UPPER_TRIM} only.")
    if not (50 <= args.seconds <= 300):
        raise TuningError("Use --seconds from 50 to 300 for reliable CLK estimates.")
    out = ROOT / "clock_logs" / ("auto_hsi_" + dt.datetime.now().strftime("%Y%m%d_%H%M%S"))
    out.mkdir(parents=True, exist_ok=False)
    print(f"Logs: {out}\nScan {args.start}..{args.end}; {args.seconds:g}s per trim")
    print("SAFETY: nominal PLL 80MHz, motor-off, watchdog-style clock checks, "
          "rollback to factory build after the run.")
    print("Keep ST-Link and USB-TTL connected. CLOSE all serial monitors.")
    result_rows = []
    flashed = False
    stop_reason = "Reached requested maximum trim."
    try:
        for trim in range(args.start, args.end + 1):
            print(f"\n===== HSITRIM {trim} =====", flush=True)
            conf = temporary_config(trim)
            # Rebuild every trim even if compiler caching or config parsing changes.
            run_command(platformio_command(AUTO_ENV, project_conf=conf, clean=True))
            flashed = True  # upload can fail after flash erase; recovery attempted
            run_command(platformio_command(AUTO_ENV, project_conf=conf))
            report, metrics = capture(args.port, args.baud, args.seconds, trim,
                                      out / f"trim{trim:02d}")
            metrics["trim"] = trim
            result_rows.append(metrics)
            print(f"  trim={trim}   TIM5={metrics['effective_tim5_hz']:.1f}Hz"
                  f"   SYSCLK={metrics['measured_sysclk_mhz']:.4f}MHz"
                  f"   error={metrics['clock_error_pct']:+.4f}%")
            # We seek near-nominal HSI; stop at FIRST crossing above nominal.
            # Current and prior can then be compared without scanning 0..31.
            if metrics["effective_tim5_hz"] >= 1_000_000:
                stop_reason = "Nominal HSI rate reached/crossed; stop ascending trim."
                break
            # Unexpected backwards step likely indicates temp drift/measurement
            # instability. Require a review rather than blindly scanning onward.
            if len(result_rows) >= 2:
                previous = result_rows[-2]["effective_tim5_hz"]
                if metrics["effective_tim5_hz"] + 1000 < previous:
                    stop_reason = "Nonmonotonic >0.1% step; manual review needed."
                    break
        if result_rows:
            best = min(result_rows, key=lambda r: abs(r["effective_tim5_hz"] - 1e6))
            print(f"\nBEST MEASURED TRIM (80MHz test): {best['trim']}, "
                  f"TIM5={best['effective_tim5_hz']:.1f} Hz; "
                  f"error={best['clock_error_pct']:+.4f}%")
            (out / "summary.json").write_text(json.dumps({
                "best_observed_trim": best["trim"],
                "stop_reason": stop_reason,
                "profile": "80MHz nominal PLL, motor OFF",
                "disclaimer": "Not approved for 100MHz operation without a new test.",
                "runs": result_rows,
            }, indent=2) + "\n", encoding="utf-8")
            with (out / "comparison.csv").open("w", encoding="utf-8-sig", newline="") as f:
                fields = ["trim", "measured_sysclk_mhz", "effective_tim5_hz",
                          "effective_tim11_hz", "clock_error_pct", "fit_records",
                          "seq_missing_count", "tx_drop_delta"]
                wr = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
                wr.writeheader()
                wr.writerows(result_rows)
        print("Stop reason:", stop_reason)
        print("Output directory:", out)
        print("DO NOT yet deploy the selected trim in a production 100MHz build.")
    finally:
        if flashed:
            print("\nRESTORING original genericSTM32F411CE firmware (100MHz nominal, "
                  "factory trim) ...", flush=True)
            try:
                run_command(platformio_command(SAFE_ENV))
                print("Original firmware restored successfully.")
            except Exception as exc:
                print("CRITICAL: Could not restore default firmware:", exc,
                      file=sys.stderr)
                print("MANUALLY RUN: python -m platformio run "
                      "-e genericSTM32F411CE --target upload",
                      file=sys.stderr)
                raise TuningError("Automatic firmware restoration FAILED") from exc


def self_test():
    # No hardware, build or serial needed. Validate configuration and decisions.
    validate_motor_off_firmware()
    s = temporary_config(22).read_text(encoding="utf-8")
    assert "[env:hsi_autotune]" in s
    assert "-DCLOCK_HSI_TRIM=22" in s
    assert "-DCLOCK_AUTOTUNE=1" in s
    assert "-DCLOCK_HSI_TRIM=20" in s  # existing tracked debug profile
    f = parse_clk("CLK,seq=1,us=1153613,ticks=1000,tx_drop=0,trim=22,fault=0,sysclk_nominal=80000000")
    assert f == {"seq": 1, "us": 1153613, "ticks": 1000, "tx_drop": 0}
    k = parse_kv("CLK,seq=1,trim=22,fault=0,sysclk_nominal=80000000")
    assert k["trim"] == "22" and k["sysclk_nominal"] == "80000000"
    # Synthetic host clock runs 0.5% faster than MCU nominal time.
    synthetic = []
    for seq in range(1, 70):
        synthetic.append({"seq": seq, "mcu_us": seq * 1_000_000,
                          "ticks": seq * 1000, "tx_drop": 0,
                          "host_perf_s": seq * 1.005,
                          "host_iso": "", "session": 0})
    analysis, *_ = analyze(synthetic)
    metrics = validate_measurement(analysis, seconds=70)
    assert abs(metrics["clock_error_pct"] + 0.497512) < 0.01, metrics
    # A dropped non-CLK UART message is a valid reason to abort a calibration
    # survey, even when the CLK sequence itself has no gaps.
    injected_bad_report = dict(analysis)
    injected_bad_report["tx_drop_delta"] = 2
    try:
        validate_measurement(injected_bad_report, seconds=70)
    except TuningError as exc:
        assert "dropped 2 messages" in str(exc), exc
    else:
        raise AssertionError("UART queue overrun must stop autotune")
    print("SELF-TEST PASSED: dynamic project config, tagged CLK parser,"
          " serial slope, safety metrics.")
    print("No board was flashed. No motor was enabled.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", default="COM7")
    parser.add_argument("--baud", type=int, default=115200)
    parser.add_argument("--start", type=int, default=20)
    parser.add_argument("--end", type=int, default=26)
    parser.add_argument("--seconds", type=float, default=60.0)
    parser.add_argument("--self-test", action="store_true",
                        help="Offline validation only; no board programming")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        else:
            autotune(args)
    except (TuningError, KeyboardInterrupt) as exc:
        print(f"\nAUTOTUNE STOPPED: {exc}", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
